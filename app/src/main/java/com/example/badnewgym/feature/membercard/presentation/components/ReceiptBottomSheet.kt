/**
 * Receipt sheet for the last recorded payment. Every line is fed from the member
 * record so the paper can never disagree with the payment tab, and the tax split
 * is computed from the amount actually charged.
 */
@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ReceiptBottomSheet(
    sheetState: SheetState,
    onDismissRequest: () -> Unit,
    invoiceNumber: String = "",
    transactionId: String = "",
    amountPaid: String = "\u20B90",
    planName: String = "",
    memberName: String = "",
    memberId: String = "",
    date: String = "",
    validityPeriod: String = "",
    paymentMethod: String = "UPI (Google Pay)",
    isSettled: Boolean = true,
    modifier: Modifier = Modifier
) {
    val context = LocalContext.current

    val amountValue = parseReceiptAmount(amountPaid)
    // Base fee plus the two 9% halves always add up to the amount on the paper.
    val baseFee = amountValue?.let { round(it / 1.18 * 100) / 100 }
    val centralTax = amountValue?.let { round(it * 0.09 / 1.18 * 100) / 100 }
    val stateTax = if (amountValue != null && baseFee != null && centralTax != null) {
        round((amountValue - baseFee - centralTax) * 100) / 100
    } else {
        null
    }

    fun shareReceipt() {
        val body = buildString {
            appendLine("BAD GYM \u2014 official receipt")
            appendLine("Member: $memberName ($memberId)")
            if (invoiceNumber.isNotBlank()) appendLine("Invoice: $invoiceNumber")
            if (transactionId.isNotBlank()) appendLine("Transaction: $transactionId")
            appendLine("Amount paid: $amountPaid")
            appendLine("Paid on: $date")
            appendLine("Plan: $planName")
            if (validityPeriod.isNotBlank()) appendLine("Validity: $validityPeriod")
            appendLine("Payment method: $paymentMethod")
            append("Generated by BAD GYM member intelligence")
        }
        val send = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "BAD GYM receipt \u2014 $memberName")
            putExtra(Intent.EXTRA_TEXT, body)
        }
        context.startActivity(Intent.createChooser(send, "Share receipt"))
    }

    ModalBottomSheet(
        onDismissRequest = onDismissRequest,
        sheetState = sheetState,
        containerColor = Color(0xFFF4FBF9),
        scrimColor = Color(0x66021C17),
        shape = RoundedCornerShape(topStart = 28.dp, topEnd = 28.dp),
        dragHandle = { SheetGrip() },
        modifier = modifier
    ) {
        Column(
            modifier = Modifier
                .fillMaxWidth()
                .padding(horizontal = 20.dp, vertical = 8.dp)
                .verticalScroll(rememberScrollState())
        ) {
            // Header Row: Close button + BAD GYM branding
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
                horizontalArrangement = Arrangement.SpaceBetween
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Box(
                        modifier = Modifier
                            .size(42.dp)
                            .shadow(
                                elevation = 6.dp,
                                shape = CircleShape,
                                ambientColor = Color(0xFF10B981),
                                spotColor = Color(0xFF10B981)
                            )
                            .clip(CircleShape)
                            .background(Brush.verticalGradient(listOf(Color(0xFF19C48A), Color(0xFF07956A))))
                            .border(1.dp, Color.White.copy(alpha = 0.5f), CircleShape),
                        contentAlignment = Alignment.Center
                    ) {
                        Icon(
                            imageVector = Icons.Default.Check,
                            contentDescription = "Paid",
                            tint = Color.White,
                            modifier = Modifier.size(23.dp)
                        )
                    }
                    Spacer(modifier = Modifier.width(10.dp))
                    Column {
                        Text(
                            text = "Official receipt",
                            color = GlassInk,
                            fontSize = 19.sp,
                            lineHeight = 23.sp,
                            fontWeight = FontWeight.Black,
                            letterSpacing = (-0.4).sp
                        )
                        Text(
                            text = "BAD GYM \u2022 BANDRA WEST",
                            color = GlassMuted,
                            fontSize = 12.sp,
                            lineHeight = 15.sp,
                            fontWeight = FontWeight.SemiBold
                        )
                    }
                }

                GlassCloseButton(onClick = onDismissRequest)
            }

            Spacer(modifier = Modifier.height(18.dp))

            // Main Receipt Paper Box
            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .neumorphicLift(RoundedCornerShape(20.dp), tint = Color(0xFF10B981), elevation = 8.dp)
                    .clip(RoundedCornerShape(20.dp))
                    .background(Brush.verticalGradient(listOf(Color.White, Color(0xFFFDFFFF), Color(0xFFF8FCFA))))
                    .border(1.dp, Color.White, RoundedCornerShape(20.dp))
                    .padding(18.dp)
            ) {
                Column(modifier = Modifier.fillMaxWidth()) {
                    // Paid Amount Banner
                    Column(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalAlignment = Alignment.CenterHorizontally
                    ) {
                        Text(
                            text = "Amount Paid",
                            color = MemberCardTokens.SlateMuted,
                            fontSize = 13.sp,
                            fontWeight = FontWeight.Medium
                        )
                        Spacer(modifier = Modifier.height(4.dp))
                        Text(
                            text = amountPaid,
                            color = MemberCardTokens.DarkNavy,
                            fontSize = 32.sp,
                            fontWeight = FontWeight.Black
                        )
                        Spacer(modifier = Modifier.height(6.dp))
                        Box(
                            modifier = Modifier
                                .clip(RoundedCornerShape(12.dp))
                                .background(if (isSettled) Color(0xFFDCFCE7) else Color(0xFFFEF3C7))
                                .padding(horizontal = 10.dp, vertical = 4.dp)
                        ) {
                            Text(
                                text = if (isSettled) {
                                    "\u2713 Payment Successful \u2022 Paid On-Time"
                                } else {
                                    "\u2713 Payment Recorded \u2022 Balance Pending"
                                },
                                color = if (isSettled) Color(0xFF15803D) else Color(0xFFB45309),
                                fontSize = 12.sp,
                                fontWeight = FontWeight.Bold
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(16.dp))

                    ReceiptDashedDivider()
                    Spacer(modifier = Modifier.height(16.dp))

                    // Receipt Metadata Rows
                    ReceiptMetaRow(label = "Member Name", value = memberName)
                    ReceiptMetaRow(label = "Membership ID", value = memberId)
                    if (invoiceNumber.isNotBlank()) {
                        ReceiptMetaRow(label = "Invoice No.", value = invoiceNumber)
                    }
                    if (transactionId.isNotBlank()) {
                        ReceiptMetaRow(label = "Transaction ID", value = transactionId)
                    }
                    ReceiptMetaRow(label = "Date & Time", value = date)
                    ReceiptMetaRow(label = "Plan", value = planName)
                    if (validityPeriod.isNotBlank()) {
                        ReceiptMetaRow(label = "Validity", value = validityPeriod)
                    }
                    ReceiptMetaRow(label = "Payment Method", value = paymentMethod)

                    if (baseFee != null && centralTax != null && stateTax != null) {
                        Spacer(modifier = Modifier.height(12.dp))
                        ReceiptDashedDivider()
                        Spacer(modifier = Modifier.height(12.dp))

                        // GST breakdown derived from the amount actually charged.
                        ReceiptMetaRow(
                            label = "Base Membership Fee",
                            value = formatReceiptAmount(baseFee),
                            isMuted = true
                        )
                        ReceiptMetaRow(
                            label = "CGST (9%)",
                            value = formatReceiptAmount(centralTax),
                            isMuted = true
                        )
                        ReceiptMetaRow(
                            label = "SGST (9%)",
                            value = formatReceiptAmount(stateTax),
                            isMuted = true
                        )

                        Spacer(modifier = Modifier.height(8.dp))
                    }

                    Row(
                        modifier = Modifier.fillMaxWidth(),
                        horizontalArrangement = Arrangement.SpaceBetween,
                        verticalAlignment = Alignment.CenterVertically
                    ) {
                        Text(
                            text = "Total Charged",
                            color = MemberCardTokens.DarkNavy,
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Black
                        )
                        Text(
                            text = amountPaid,
                            color = MemberCardTokens.DarkNavy,
                            fontSize = 15.sp,
                            fontWeight = FontWeight.Black
                        )
                    }
                }
            }

            Spacer(modifier = Modifier.height(18.dp))

            Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .neumorphicLift(RoundedCornerShape(50.dp), tint = Color(0xFF10B981), elevation = 7.dp)
                    .clip(RoundedCornerShape(50.dp))
                    .background(Brush.horizontalGradient(listOf(Color(0xFF19C48A), Color(0xFF0FA875), Color(0xFF07956A))))
                    .border(1.dp, Color.White.copy(alpha = 0.4f), RoundedCornerShape(50.dp))
                    .clickable { shareReceipt() }
                    .padding(vertical = 15.dp),
                contentAlignment = Alignment.Center
            ) {
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Icon(
                        imageVector = Icons.Default.Share,
                        contentDescription = null,
                        tint = Color.White,
                        modifier = Modifier.size(17.dp)
                    )
                    Spacer(modifier = Modifier.width(7.dp))
                    Text(
                        text = "Share receipt",
                        fontSize = 15.sp,
                        fontWeight = FontWeight.Black,
                        color = Color.White,
                        letterSpacing = 0.1.sp
                    )
                }
            }

            Spacer(modifier = Modifier.height(24.dp))
        }
    }
}

@Composable
private fun ReceiptDashedDivider() {
    Canvas(
        modifier = Modifier
            .fillMaxWidth()
            .height(1.dp)
    ) {
        drawLine(
            color = Color(0xFFCBD5E1),
            start = Offset(0f, 0f),
            end = Offset(size.width, 0f),
            pathEffect = PathEffect.dashPathEffect(floatArrayOf(12f, 8f), 0f),
            strokeWidth = 1.dp.toPx()
        )
    }
}

@Composable
private fun ReceiptMetaRow(
    label: String,
    value: String,
    isMuted: Boolean = false
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(vertical = 3.dp),
        horizontalArrangement = Arrangement.SpaceBetween,
        verticalAlignment = Alignment.CenterVertically
    ) {
        Text(
            text = label,
            color = if (isMuted) Color(0xFF94A3B8) else Color(0xFF64748B),
            fontSize = if (isMuted) 10.5.sp else 11.sp,
            fontWeight = FontWeight.Medium
        )
        Text(
            text = value.ifBlank { "\u2014" },
            color = if (isMuted) Color(0xFF64748B) else MemberCardTokens.DarkNavy,
            fontSize = if (isMuted) 10.5.sp else 11.sp,
            fontWeight = FontWeight.Bold,
            textAlign = TextAlign.End
        )
    }
}

/** Reads "₹2,800", "Rs. 800.50" or "800" as a number; null when no digits exist. */
private fun parseReceiptAmount(raw: String): Double? =
    Regex("\\d[\\d,]*(?:\\.\\d+)?").find(raw)
        ?.value
        ?.replace(",", "")
        ?.toDoubleOrNull()

/** Formats a value with Indian digit grouping and two decimals. */
private fun formatReceiptAmount(amount: Double): String {
    val rounded = round(amount * 100) / 100
    val wholePart = rounded.toLong()
    val paise = round((rounded - wholePart) * 100).toInt()

    val digits = wholePart.toString()
    val grouped = if (digits.length <= 3) {
        digits
    } else {
        val head = digits.dropLast(3)
        val groups = mutableListOf<String>()
        var end = head.length
        while (end > 0) {
            val start = (end - 2).coerceAtLeast(0)
            groups.add(0, head.substring(start, end))
            end = start
        }
        groups.joinToString(",") + "," + digits.takeLast(3)
    }
    return "\u20B9$grouped.${paise.toString().padStart(2, '0')}"
}
